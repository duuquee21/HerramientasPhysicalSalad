using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Studio.Audio.EditorTools
{
    /// Genera, a partir del catálogo, el archivo AudioIds.cs (constantes para usar en el código)
    /// y la guía para el equipo de sonido.
    public static class AudioCodeGenerator
    {
        // ───────────── AudioIds.cs ─────────────
        public static void GenerateIds(AudioCatalogAsset catalog)
        {
            string path = AudioEditorPaths.Root + "/AudioIds.cs";
            var used = new HashSet<string>();
            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generado desde el AudioCatalog (Tools > Audio Manager > 3. Generar AudioIds.cs). No lo edites a mano.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("public static class AudioIds");
            sb.AppendLine("{");

            foreach (var e in catalog.events) AddId(sb, used, e.id);
            sb.AppendLine();
            foreach (var t in catalog.tracks) AddId(sb, used, t.id);

            sb.AppendLine("}");

            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
            Debug.Log($"[Audio] AudioIds.cs generado con {used.Count} ids: {path}");
        }

        static void AddId(StringBuilder sb, HashSet<string> used, string id)
        {
            if (string.IsNullOrWhiteSpace(id)) return;

            string name = Identifier(id.Trim());
            if (!used.Add(name))
            {
                Debug.LogWarning($"[Audio] Id repetido o equivalente en el catálogo: '{id}'. Se ignora.");
                return;
            }

            sb.AppendLine($"    public const string {name} = \"{id.Trim()}\";");
        }

        static string Identifier(string id)
        {
            var sb = new StringBuilder();
            foreach (char c in id) sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, '_');
            return sb.ToString();
        }

        // ───────────── Guía para el equipo de sonido ─────────────
        public static void GenerateGuide(AudioCatalogAsset catalog)
        {
            string path = AudioEditorPaths.Root + "/LEEME_Audio.md";
            string project = string.IsNullOrEmpty(Application.productName) ? "el juego" : Application.productName;

            var sb = new StringBuilder();
            sb.AppendLine($"# Guía de audio — {project}");
            sb.AppendLine();
            sb.AppendLine("Esta guía es para quien hace el sonido y la música. **No hace falta saber programar ni saber Unity.**");
            sb.AppendLine();
            sb.AppendLine("## Cómo funciona, en una frase");
            sb.AppendLine();
            sb.AppendLine("El juego avisa de lo que pasa y cada aviso tiene un **evento de sonido**. Tú decides qué suena en cada evento. No hay que tocar código.");
            sb.AppendLine();
            sb.AppendLine("## Dónde va cada cosa");
            sb.AppendLine();
            sb.AppendLine("Todo está dentro de `" + AudioEditorPaths.Root + "/`:");
            sb.AppendLine();
            sb.AppendLine("| Carpeta | Qué lleva |");
            sb.AppendLine("|---|---|");
            sb.AppendLine("| `UI/` | Sonidos de la interfaz (botones, paneles, compras) |");
            sb.AppendLine("| `SFX/` | Efectos del juego |");
            sb.AppendLine("| `Ambiente/` | Sonidos ambiente en bucle |");
            sb.AppendLine("| `Musica/` | Las pistas de música |");
            sb.AppendLine("| `Eventos/` | Los \"eventos\" (no hace falta tocarlos, ver más abajo) |");
            sb.AppendLine();
            sb.AppendLine("## Cómo añadir un sonido (lo fácil)");
            sb.AppendLine();
            sb.AppendLine("1. Exporta el sonido como **WAV** y ponle **el nombre del evento**, seguido de un número si hay varias versiones:");
            sb.AppendLine("   `UI_Click_01.wav`, `UI_Click_02.wav`, `UI_Click_03.wav`");
            sb.AppendLine("2. Copia los archivos a la carpeta que toque.");
            sb.AppendLine("3. Abre Unity y espera unos segundos: **se asignan solos**. Ya está.");
            sb.AppendLine();
            sb.AppendLine("Si hay varias versiones del mismo evento, el juego elige una al azar sin repetir la anterior.");
            sb.AppendLine();
            sb.AppendLine("Para la **música**, el nombre es el de la pista. Si tiene intro, se añade `_Intro`: `Music_Main_Intro.wav` (suena una vez) y `Music_Main.wav` (el bucle).");
            sb.AppendLine();
            sb.AppendLine("## Probar lo que has hecho");
            sb.AppendLine();
            sb.AppendLine("Menú de Unity **Tools > Audio Manager > Panel de pruebas**: lista todos los eventos y pistas, dice cuáles ya tienen sonido (✔) y cuáles faltan (✗), y permite escuchar cada uno con el botón **▶**.");
            sb.AppendLine();
            sb.AppendLine("En `Eventos/` hay un archivo por evento. Al hacer clic en uno verás sus ajustes, con un botón **▶ Probar**. Si no suena, activa el icono del altavoz de la barra de la vista *Scene*.");
            sb.AppendLine();
            sb.AppendLine("- **Volume Db**: volumen en decibelios (0 = sin cambios, −6 = la mitad, −12 = un cuarto).");
            sb.AppendLine("- **Volume Variation Db**: cuánto varía el volumen al azar en cada reproducción (0 a 2 queda natural).");
            sb.AppendLine("- **Pitch Semitones** y **Pitch Variation Semitones**: tono fijo y variación al azar, en semitonos.");
            sb.AppendLine("- **Cooldown Seconds**: tiempo mínimo entre dos reproducciones (evita ráfagas).");
            sb.AppendLine("- **Max Instances**: cuántas copias pueden sonar a la vez.");
            sb.AppendLine("- **Play In Background**: si suena cuando el jugador está en otro programa.");
            sb.AppendLine("- **Duck Music Db / Duck Seconds**: cuánto baja la música mientras suena este evento, y durante cuánto tiempo.");
            sb.AppendLine();
            sb.AppendLine("Todo lo que no toques se queda con valores razonables ya puestos.");
            sb.AppendLine();
            sb.AppendLine("## Especificaciones técnicas");
            sb.AppendLine();
            sb.AppendLine("- **Formato:** WAV, 44,1 o 48 kHz, 16 o 24 bits. No MP3 (mete silencio al inicio y rompe los bucles).");
            sb.AppendLine("- **Efectos e interfaz:** picos máximos a **−3 dBFS**, sin recortes, sin silencio al principio ni al final.");
            sb.AppendLine("- **Música:** unos **−16 LUFS** integrados, picos máximos a −1 dBTP.");
            sb.AppendLine("- **Bucles** (música y ambiente): cortados exactamente en el punto de unión, sin fundidos en los extremos.");
            sb.AppendLine("- Los sonidos que se repiten mucho tienen que ser muy cortos y suaves.");
            sb.AppendLine();
            sb.AppendLine("## Lista de eventos");
            sb.AppendLine();
            sb.AppendLine("| Evento (nombre del archivo) | Carpeta | Bucle | Cuándo suena |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var e in catalog.events)
            {
                if (string.IsNullOrWhiteSpace(e.id)) continue;
                sb.AppendLine($"| `{e.id}` | {FolderFor(e.bus)} | {(e.loop ? "sí" : "no")} | {Clean(e.description)} |");
            }

            sb.AppendLine();
            sb.AppendLine("## Pistas de música");
            sb.AppendLine();
            sb.AppendLine("| Pista | Cuándo suena |");
            sb.AppendLine("|---|---|");
            foreach (var t in catalog.tracks)
            {
                if (string.IsNullOrWhiteSpace(t.id)) continue;
                sb.AppendLine($"| `{t.id}` | {Clean(t.description)} |");
            }

            if (!string.IsNullOrWhiteSpace(catalog.guideNotes))
            {
                sb.AppendLine();
                sb.AppendLine("## Notas de este proyecto");
                sb.AppendLine();
                sb.AppendLine(catalog.guideNotes.Trim());
            }

            sb.AppendLine();
            sb.AppendLine("## Preguntas frecuentes");
            sb.AppendLine();
            sb.AppendLine("**He añadido un sonido y no suena.** Comprueba que el nombre del archivo empieza *exactamente* por el nombre del evento (mayúsculas incluidas) y que está dentro de la carpeta de audio. Después, **Tools > Audio Manager > 5. Informe de cobertura** te dice qué eventos siguen sin sonido.");
            sb.AppendLine();
            sb.AppendLine("**Quiero cambiar un sonido.** Sustituye el archivo por otro con el mismo nombre.");
            sb.AppendLine();
            sb.AppendLine("**Necesito un evento que no está en la lista.** Pídeselo al equipo de programación: se añade en un minuto.");

            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
            Debug.Log("[Audio] Guía generada: " + path);
        }

        static string FolderFor(AudioBus bus)
        {
            switch (bus)
            {
                case AudioBus.Ui: return "UI";
                case AudioBus.Ambience: return "Ambiente";
                case AudioBus.Music: return "Musica";
                default: return "SFX";
            }
        }

        static string Clean(string text) => string.IsNullOrEmpty(text) ? "" : text.Replace("|", "/").Replace("\n", " ").Trim();
    }
}
